#!/usr/bin/env python3
"""Boss tactics for the companions: docker/companions/tactics/*.json -> docker/sql/world/<file>.sql (world.companion_boss_tactics).

One JSON file per instance:
  {"instance": "Stratholme", "map": 329, "aliases": ["strat"],
   "bosses": [{"name": "Baron Rivendare", "wing": "Undead side", "aliases": ["baron"],
               "general": "...", "tank": "...", "healer": "...", "dps": "..."}]}
"name" is the creature's name in the game (the bots match targets by it), "aliases" what players call it. Lines are said in
chat: "general" at most 200 characters, each role at most 230.

usage: scripts/gen-tactics.py            (writes the SQL file, fails on a line too long)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docker" / "companions" / "tactics"
OUTPUT = ROOT / "docker" / "sql" / "world" / "2026_10_26_92_world_companions_boss_tactics.sql"
LIMITS = {"general": 200, "tank": 230, "healer": 230, "dps": 230}


def sql(text):
    return "'" + str(text).replace("\\", "\\\\").replace("'", "''") + "'"


def main():
    rows, errors, maps = [], [], set()
    for path in sorted(SOURCE.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if data["map"] in maps and data["map"] != 229 and data["map"] != 0 and data["map"] != 1:
            errors.append(f"{path.name}: map {data['map']} twice")
        maps.add(data["map"])
        names = set()
        for sort, boss in enumerate(data["bosses"], 1):
            if boss["name"] in names:
                errors.append(f"{path.name}: {boss['name']} twice")
            names.add(boss["name"])
            for key, limit in LIMITS.items():
                if len(boss.get(key, "")) > limit:
                    errors.append(f"{path.name}: {boss['name']} {key} is {len(boss[key])} characters (at most {limit})")
            if not boss.get("general"):
                errors.append(f"{path.name}: {boss['name']} has no general line")
            rows.append((data["map"], data.get("sort_base", 0) + sort, data["instance"], ",".join(data.get("aliases", [])),
                         boss.get("wing", ""), boss["name"], ",".join(boss.get("aliases", [])), boss["general"],
                         boss.get("tank", ""), boss.get("healer", ""), boss.get("dps", "")))
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1

    out = [
        "-- Companions: boss tactics by role, for the companions and the brain (CompanionTactics.cpp).",
        "-- Generated by scripts/gen-tactics.py from docker/companions/tactics/*.json: edit those and run it again.",
        "CREATE TABLE IF NOT EXISTS `companion_boss_tactics` (",
        "  `map` INT UNSIGNED NOT NULL,",
        "  `sort` SMALLINT UNSIGNED NOT NULL,",
        "  `instance` VARCHAR(64) NOT NULL,",
        "  `instance_aliases` VARCHAR(255) NOT NULL DEFAULT '',",
        "  `wing` VARCHAR(64) NOT NULL DEFAULT '',",
        "  `boss` VARCHAR(64) NOT NULL,",
        "  `aliases` VARCHAR(255) NOT NULL DEFAULT '',",
        "  `general` VARCHAR(255) NOT NULL,",
        "  `tank` VARCHAR(255) NOT NULL DEFAULT '',",
        "  `healer` VARCHAR(255) NOT NULL DEFAULT '',",
        "  `dps` VARCHAR(255) NOT NULL DEFAULT '',",
        "  PRIMARY KEY (`map`, `boss`)",
        ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Companions: boss tactics by role (docker/companions/tactics)';",
        "",
        "DELETE FROM `companion_boss_tactics`;",
    ]
    columns = "`map`, `sort`, `instance`, `instance_aliases`, `wing`, `boss`, `aliases`, `general`, `tank`, `healer`, `dps`"
    for start in range(0, len(rows), 50):
        chunk = rows[start:start + 50]
        out.append(f"INSERT INTO `companion_boss_tactics` ({columns}) VALUES")
        out.append(",\n".join("(" + ", ".join(str(v) if isinstance(v, int) else sql(v) for v in row) + ")" for row in chunk) + ";")
    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(rows)} bosses in {len(maps)} instances -> {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
